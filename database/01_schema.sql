
-- ============================================================================
-- JoyGames - 01_schema.sql
-- Creates the database, tables, constraints, and indexes.
-- ============================================================================

IF DB_ID('JoyGamesDb') IS NULL
BEGIN
    CREATE DATABASE JoyGamesDb;
END
GO

USE JoyGamesDb;
GO

-- ============================================================================
-- ROLES
-- ============================================================================

-- User roles synchronized with JoyGames.Core.Enums.UserRole.
IF OBJECT_ID('dbo.Roles', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.Roles (
        Id   INT          NOT NULL PRIMARY KEY,
        Name NVARCHAR(50) NOT NULL UNIQUE
    );
END
GO

-- ============================================================================
-- STATES
-- ============================================================================

-- User and contact states synchronized with their Core enums.
IF OBJECT_ID('dbo.States', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.States (
        Id   INT          NOT NULL PRIMARY KEY,
        Name NVARCHAR(50) NOT NULL UNIQUE
    );
END
GO

-- ============================================================================
-- CATEGORIES
-- ============================================================================

IF OBJECT_ID('dbo.Categories', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.Categories (
        Id   INT          IDENTITY(1,1) NOT NULL PRIMARY KEY,
        Name NVARCHAR(80) NOT NULL UNIQUE
    );
END
GO

-- ============================================================================
-- COMPANIES
-- ============================================================================

IF OBJECT_ID('dbo.Companies', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.Companies (
        Id      INT           IDENTITY(1,1) NOT NULL PRIMARY KEY,
        Name    NVARCHAR(100) NOT NULL UNIQUE,
        Country NVARCHAR(80)  NOT NULL
    );
END
GO

-- ============================================================================
-- USERS
-- ============================================================================

-- Uses UUIDv7 identifiers generated by the .NET application.
-- Password stores the BCrypt hash generated by the application.
IF OBJECT_ID('dbo.Users', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.Users (
        Id        UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
        Name      NVARCHAR(100)    NOT NULL,
        Email     NVARCHAR(150)    NOT NULL UNIQUE,
        UserName  NVARCHAR(50)     NOT NULL UNIQUE,
        Password  NVARCHAR(255)    NOT NULL,
        UserRole  INT              NOT NULL,
        UserState INT              NOT NULL,
        CreatedAt DATETIME2        NOT NULL
            CONSTRAINT DF_Users_CreatedAt DEFAULT SYSUTCDATETIME(),

        CONSTRAINT FK_Users_Roles
            FOREIGN KEY (UserRole) REFERENCES dbo.Roles(Id),

        CONSTRAINT FK_Users_States
            FOREIGN KEY (UserState) REFERENCES dbo.States(Id)
    );
END
GO

-- ============================================================================
-- GAMES
-- ============================================================================

-- Uses UUIDv7 identifiers generated by the .NET application.
IF OBJECT_ID('dbo.Games', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.Games (
        Id          UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
        Title       NVARCHAR(150)    NOT NULL,
        Description NVARCHAR(MAX)    NOT NULL,
        CategoryId  INT              NOT NULL,
        CompanyId   INT              NOT NULL,
        ReleaseDate DATETIME2        NOT NULL,
        SoldCopies  BIGINT           NOT NULL
            CONSTRAINT DF_Games_SoldCopies DEFAULT 0,
        ImageUrl    NVARCHAR(500)    NULL,
        TrailerUrl  NVARCHAR(500)    NULL,
        CreatedAt   DATETIME2        NOT NULL
            CONSTRAINT DF_Games_CreatedAt DEFAULT SYSUTCDATETIME(),

        CONSTRAINT FK_Games_Categories
            FOREIGN KEY (CategoryId) REFERENCES dbo.Categories(Id),

        CONSTRAINT FK_Games_Companies
            FOREIGN KEY (CompanyId) REFERENCES dbo.Companies(Id),

        CONSTRAINT CK_Games_SoldCopies
            CHECK (SoldCopies >= 0)
    );
END
GO

-- ============================================================================
-- CONTACTS
-- ============================================================================

IF OBJECT_ID('dbo.Contacts', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.Contacts (
        Id      UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
        Message NVARCHAR(1000)   NOT NULL,
        Email   NVARCHAR(150)    NOT NULL,
        State   INT              NOT NULL,
        SentAt  DATETIME2        NOT NULL
            CONSTRAINT DF_Contacts_SentAt DEFAULT SYSUTCDATETIME(),

        CONSTRAINT FK_Contacts_States
            FOREIGN KEY (State) REFERENCES dbo.States(Id)
    );
END
GO

-- ============================================================================
-- INDEXES
-- ============================================================================

-- Creates indexes independently of table creation.
IF NOT EXISTS (
    SELECT 1
    FROM sys.indexes
    WHERE name = 'IX_Games_CategoryId'
      AND object_id = OBJECT_ID('dbo.Games')
)
BEGIN
    CREATE NONCLUSTERED INDEX IX_Games_CategoryId
    ON dbo.Games(CategoryId);
END
GO

IF NOT EXISTS (
    SELECT 1
    FROM sys.indexes
    WHERE name = 'IX_Games_CompanyId'
      AND object_id = OBJECT_ID('dbo.Games')
)
BEGIN
    CREATE NONCLUSTERED INDEX IX_Games_CompanyId
    ON dbo.Games(CompanyId);
END
GO

-- Prevents duplicate game titles for the same company.
IF NOT EXISTS (
    SELECT 1
    FROM sys.indexes
    WHERE name = 'UX_Games_Title_CompanyId'
      AND object_id = OBJECT_ID('dbo.Games')
)
BEGIN
    IF EXISTS (
        SELECT 1
        FROM dbo.Games
        GROUP BY Title, CompanyId
        HAVING COUNT(*) > 1
    )
    BEGIN
        THROW 50001,
            'Duplicate game titles exist for the same company.',
            1;
    END

    CREATE UNIQUE NONCLUSTERED INDEX UX_Games_Title_CompanyId
    ON dbo.Games(Title, CompanyId);
END
GO

IF NOT EXISTS (
    SELECT 1
    FROM sys.indexes
    WHERE name = 'IX_Contacts_State'
      AND object_id = OBJECT_ID('dbo.Contacts')
)
BEGIN
    CREATE NONCLUSTERED INDEX IX_Contacts_State
    ON dbo.Contacts(State);
END
GO
